
// 1. Mathematical Constants
console.log("PI:", Math.PI);
console.log("Euler's Number:", Math.E);

// 2. Rounding Methods
console.log("\nRound:", Math.round(4.6));
console.log("Floor:", Math.floor(4.9));
console.log("Ceil:", Math.ceil(4.1));

// 3. Absolute Value
console.log("\nAbsolute Value:", Math.abs(-7));

// 4. Maximum and Minimum
console.log("Maximum:", Math.max(1, 5, 3));
console.log("Minimum:", Math.min(1, 5, 3));

// 5. Power and Square Root
console.log("\nPower:", Math.pow(2, 10));
console.log("Square Root:", Math.sqrt(16));

// 6. Random Number
console.log("\nRandom Number:", Math.random());

// 7. Random Integer Between 1 and 10
let randomNumber = Math.floor(Math.random() * 10) + 1;
console.log("Random Integer (1-10):", randomNumber);
