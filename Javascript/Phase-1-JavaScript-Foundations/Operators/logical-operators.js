
let a = true;
let b = false;

// 1. Logical AND (&&)
console.log("AND (a && b):", a && b);

// 2. Logical OR (||)
console.log("OR (a || b):", a || b);

// 3. Logical NOT (!)
console.log("NOT (!a):", !a);
console.log("NOT (!b):", !b);

// 4. Combining Logical Operators
console.log("AND (true && true):", true && true);
console.log("OR (false || false):", false || false);
