
// 1. Embedding Variables
let name = "Aman";
let age = 25;

console.log(`Hello, my name is ${name} and I am ${age} years old.`);


// 2. Embedding Expressions
let a = 10;
let b = 5;

console.log(`Sum: ${a + b}`);
console.log(`Is Aman an adult? ${age >= 18}`);


// 3. Multi-line Strings
let poem = `Roses are red,
Violets are blue,
JS is awesome,
And so are you.`;

console.log("\nPoem:");
console.log(poem);


// 4. Comparing with String Concatenation
let firstName = "Aman";
let lastName = "Kumar";

console.log(`Full Name: ${firstName} ${lastName}`);
