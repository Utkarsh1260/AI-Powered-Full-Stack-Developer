
// 1. Single Quotes
let s1 = 'Single quotes';

// 2. Double Quotes
let s2 = "Double quotes";

// 3. Backticks (Template Literals)
let s3 = `Backticks (template literals)`;

// 4. Display Strings
console.log("Single Quotes:", s1);
console.log("Double Quotes:", s2);
console.log("Backticks:", s3);

// 5. Checking Data Types
console.log("Type of s1:", typeof s1);
console.log("Type of s2:", typeof s2);
console.log("Type of s3:", typeof s3);

// 6. Template Literal with Variables
let namee = "Aman";
let age = 25;

console.log(`My name is ${namee} and I am ${age} years old.`);
